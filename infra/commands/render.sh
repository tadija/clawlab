append_unique() {
  local value="$1"
  local existing

  [[ -n "$value" ]] || return 0

  for existing in "${BREW_PACKAGES[@]:-}"; do
    [[ "$existing" != "$value" ]] || return 0
  done

  BREW_PACKAGES+=("$value")
}

append_unique_tap() {
  local value="$1"
  local existing

  [[ -n "$value" ]] || return 0

  for existing in "${BREW_TAPS[@]:-}"; do
    [[ "$existing" != "$value" ]] || return 0
  done

  BREW_TAPS+=("$value")
}

append_unique_cask() {
  local value="$1"
  local existing

  [[ -n "$value" ]] || return 0

  for existing in "${BREW_CASKS[@]:-}"; do
    [[ "$existing" != "$value" ]] || return 0
  done

  BREW_CASKS+=("$value")
}

append_list() {
  local raw="$1"
  local item

  raw="$(trim_commas "$raw")"
  [[ -n "$raw" ]] || return 0
  # shellcheck disable=SC2206
  local -a items=($raw)
  for item in "${items[@]}"; do
    append_unique "$item"
  done
}

append_tap_list() {
  local raw="$1"
  local item

  raw="$(trim_commas "$raw")"
