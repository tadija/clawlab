html_escape() {
  local value="$1"
  value="${value//&/&amp;}"
  value="${value//</&lt;}"
  value="${value//>/&gt;}"
  value="${value//\"/&quot;}"
  printf '%s' "$value"
}

js_single_quote_escape() {
  local value="$1"
  value="${value//\\/\\\\}"
  value="${value//$'\n'/\\n}"
  value="${value//\'/\\\'}"
  printf '%s' "$value"
}

url_encode_path_segment() {
  local value="$1"
  local length="${#value}"
  local index
  local char
  local encoded=""

  for ((index = 0; index < length; index++)); do
    char="${value:index:1}"
    case "$char" in
      [a-zA-Z0-9._~-])
        encoded+="$char"
        ;;
      *)
        printf -v char '%%%02X' "'$char"
        encoded+="$char"
        ;;
    esac
  done

  printf '%s' "$encoded"
}

render_tailscale_nav_html() {
  local current="$1"
  local alias
  local url
  local class_name
  local label

  while IFS=$'\t' read -r alias url; do
    [[ -n "$alias" && -n "$url" ]] || continue
    class_name="segmented-link"
    label="$(normalize_host_alias "$alias")"
    if [[ "$label" == "$current" ]]; then
      class_name="segmented-link is-active"
    fi
    printf '        <a class="%s" href="%s" data-host-shortcut>%s</a>\n' \
      "$(html_escape "$class_name")" \
      "$(html_escape "$url")" \
      "$(html_escape "$label")"
  done < <(tailscale_nav_entries)
}

render_commit_hash() {
  git -C "$(repo_root)" rev-parse --short HEAD 2>/dev/null || printf '%s' "unknown"
}

agent_gateway_port() {
  local agent_id="$1"
  repo_cfg_value "agent-ports" "$agent_id"
}

agent_status_for_start_args() {
  local agent_id="$1"
  local start_args="$2"
  local state
  local label

  if [[ -z "$start_args" ]]; then
    printf '%s' "interactive"
    return
  fi

  if is_linux; then
    state="$(systemd_service_state "agent@${agent_id}")"
    case "$state" in
      active) printf '%s' "running" ;;
      inactive|failed|activating|deactivating) printf '%s' "$state" ;;
      *) printf '%s' "unavailable" ;;
    esac
    return
  fi

  if is_macos; then
    label="$(service_label_for_agent "$agent_id")"
    state="$(launchd_service_state "$label")"
    if [[ "$state" == "running" ]]; then
      printf '%s' "running"
    elif [[ -f "/Library/LaunchDaemons/${label}.plist" ]]; then
      printf '%s' "configured"
    else
      printf '%s' "unavailable"
    fi
    return
  fi

  printf '%s' "unknown"
}

prepare_agent_render_cache() {
  local agent_id
  local dir_name
  local kind
  local port
  local start_args
  local status
  local tui_args
  local tui_yolo_args

  RENDER_AGENT_IDS=()
  RENDER_AGENT_NAMES=()
  RENDER_AGENT_PORTS=()
  RENDER_AGENT_STATUSES=()
  RENDER_AGENT_TUI_ARGS=()
  RENDER_AGENT_TUI_YOLO_ARGS=()
  RENDER_AGENT_START_ARGS=()

  for agent_id in "$@"; do
    [[ -n "$agent_id" ]] || continue
    kind="$(known_agent_kind_for_id "$agent_id")" || continue
    dir_name="$(agent_directory_name "$agent_id")"
    port="$(agent_gateway_port "$agent_id")"
    load_agent_kind_definition "$kind"
    tui_args="${AELAB_AGENT_TUI_ARGS:-}"
    tui_yolo_args="${AELAB_AGENT_TUI_YOLO_ARGS:-}"
    start_args="${AELAB_AGENT_START_ARGS:-}"
    status="$(agent_status_for_start_args "$agent_id" "$start_args")"

    RENDER_AGENT_IDS+=("$agent_id")
    RENDER_AGENT_NAMES+=("$dir_name")
    RENDER_AGENT_PORTS+=("$port")
    RENDER_AGENT_STATUSES+=("$status")
    RENDER_AGENT_TUI_ARGS+=("$tui_args")
    RENDER_AGENT_TUI_YOLO_ARGS+=("$tui_yolo_args")
    RENDER_AGENT_START_ARGS+=("$start_args")
  done
}

render_agent_links_html() {
  local agent_id
  local dir_name
  local index
  local port
  local status
  local status_class
  local actions_html
  local details_html
  local title_html
  local tui_args
  local tui_url

  for index in "${!RENDER_AGENT_IDS[@]}"; do
    agent_id="${RENDER_AGENT_IDS[$index]}"
    dir_name="${RENDER_AGENT_NAMES[$index]}"
    port="${RENDER_AGENT_PORTS[$index]}"
    status="${RENDER_AGENT_STATUSES[$index]}"
    tui_args="${RENDER_AGENT_TUI_ARGS[$index]}"
    status_class="$(status_class_for_state "$status")"
    actions_html="$(render_action_menu_html "$agent_id")"
    if [[ -n "$tui_args" ]]; then
      tui_url="/tty/${agent_id}/tui/"
      title_html="<a href=\"$(html_escape "$tui_url")\" target=\"_blank\" rel=\"noreferrer\">$(html_escape "$dir_name")</a>"
    else
      title_html="<span class=\"item-name\">$(html_escape "$dir_name")</span>"
    fi
    details_html=""
    if [[ -n "$port" ]]; then
      details_html="<span class=\"detail-port\">port: <code>$(html_escape "$port")</code></span>"
    fi
    render_index_row_html "$title_html" "$status_class" "$status" "$details_html" "$actions_html"
  done
}

status_class_for_state() {
  local status="$1"

  if [[ "$status" == "running" || "$status" == "active" ]]; then
    printf 'status-running'
  elif [[ "$status" == "configured" || "$status" == "inactive" || "$status" == "activating" || "$status" == "deactivating" ]]; then
    printf 'status-configured'
  elif [[ "$status" == "interactive" ]]; then
    printf 'status-interactive'
  elif [[ "$status" == "unavailable" || "$status" == "failed" || "$status" == "unloaded" ]]; then
    printf 'status-unavailable'
  else
    printf 'status-unknown'
  fi
}

render_index_row_html() {
  local title_html="$1"
  local status_class="$2"
  local status="$3"
  local details_html="$4"
  local actions_html="$5"
  local status_html=""
  local actions_block=""

  if [[ -n "$status" ]]; then
    status_html=" <span class=\"$(html_escape "$status_class")\">$(html_escape "$status")</span>"
  fi
  if [[ -n "$actions_html" ]]; then
    actions_block="<div class=\"row-actions\">${actions_html}</div>"
  fi

  printf '        <li class="index-row"><div class="row-main"><div class="row-title">%s%s</div><div class="row-details">%s</div></div>%s</li>\n' \
    "$title_html" \
    "$status_html" \
    "$details_html" \
    "$actions_block"
}

render_service_links_html() {
  local service_id
  local route
  local route_port
  local route_html
  local service_id_html
  local status
  local status_class
  local title_html
  local details_html

  while IFS= read -r service_id; do
    [[ -n "$service_id" ]] || continue
    load_service_definition "$service_id"
    status="$(service_status "$service_id")"
    status_class="$(status_class_for_state "$status")"
    case "$status" in
      running|active|interactive) ;;
      *) continue ;;
    esac
    route="$(expand_runtime_placeholders "${AELAB_SERVICE_CADDY_ROUTE:-}")"
    service_id_html="$(html_escape "$service_id")"
    if [[ "$route" == /* ]]; then
      route_html="$(html_escape "$route")"
      local managed_port_html=""
      if [[ -n "${AELAB_SERVICE_PORT:-}" ]]; then
        managed_port_html="<span class=\"detail-port\">port: <code>$(html_escape "$AELAB_SERVICE_PORT")</code></span>"
      fi
      title_html="<a href=\"$(html_escape "${route%/}/")\" target=\"_blank\" rel=\"noreferrer\">${service_id_html}</a>"
      details_html="${managed_port_html}${managed_port_html:+ }<span class=\"detail-path\">path: <code>${route_html}</code></span>"
      render_index_row_html "$title_html" "$status_class" "$status" "$details_html" ""
      continue
    fi
    if [[ "$route" == :* ]]; then
      route_port="${route#:}"
      route_html="$(html_escape "$route_port")"
      title_html="<span class=\"item-name\">${service_id_html}</span>"
      details_html="<span class=\"detail-port\">port: <code>${route_html}</code></span>"
      render_index_row_html "$title_html" "$status_class" "$status" "$details_html" ""
      continue
    fi
    if [[ -n "$route" ]]; then
      route_html="$(html_escape "$route")"
      title_html="<span class=\"item-name\">${service_id_html}</span>"
      details_html="<span>host: <code>${route_html}</code></span>"
      render_index_row_html "$title_html" "$status_class" "$status" "$details_html" ""
      continue
    fi
    title_html="<span class=\"item-name\">${service_id_html}</span>"
    render_index_row_html "$title_html" "$status_class" "$status" "" ""
  done < <(requested_service_ids_from_env)
}

render_action_menu_html() {
  local target="$1"
  local agent_id
  local agent_html=""
  local dir_name
  local index
  local interactive_agent_html=""
  local start_args
  local tui_args
  local option_url
  local shell_url
  local tool_html=""
  local sections_html=""
  local yolo_agent_html=""
  local tui_yolo_args
  local status

  shell_url="/tty/$(url_encode_path_segment "$target")/"
  tool_html+="            <a class=\"action-menu-item\" href=\"$(html_escape "$shell_url")\" target=\"_blank\" rel=\"noreferrer\">shell</a>"$'\n'

  for index in "${!RENDER_AGENT_IDS[@]}"; do
    agent_id="${RENDER_AGENT_IDS[$index]}"
    [[ -n "$agent_id" ]] || continue
    dir_name="${RENDER_AGENT_NAMES[$index]}"
    option_url="/tty/$(url_encode_path_segment "$target")/${agent_id}/tui/"
    tui_args="${RENDER_AGENT_TUI_ARGS[$index]}"
    [[ -n "$tui_args" ]] || continue
    start_args="${RENDER_AGENT_START_ARGS[$index]}"
    status="${RENDER_AGENT_STATUSES[$index]}"
    if [[ -z "$start_args" ]]; then
      interactive_agent_html+="            <a class=\"action-menu-item\" href=\"$(html_escape "$option_url")\" target=\"_blank\" rel=\"noreferrer\">$(html_escape "$dir_name")</a>"$'\n'
    elif [[ "$status" == "running" || "$status" == "active" ]]; then
      agent_html+="            <a class=\"action-menu-item\" href=\"$(html_escape "$option_url")\" target=\"_blank\" rel=\"noreferrer\">$(html_escape "$dir_name")</a>"$'\n'
    fi
    tui_yolo_args="${RENDER_AGENT_TUI_YOLO_ARGS[$index]}"
    if [[ -n "$tui_yolo_args" ]]; then
      option_url="/tty/$(url_encode_path_segment "$target")/${agent_id}/yolo/"
      yolo_agent_html+="            <a class=\"action-menu-item action-menu-item-yolo\" href=\"$(html_escape "$option_url")\" target=\"_blank\" rel=\"noreferrer\">$(html_escape "$dir_name")</a>"$'\n'
    fi
  done

  sections_html+="            <div class=\"action-menu-section\" data-open-with-section data-terminal-path=\"$(html_escape "$shell_url")\">"$'\n'
  sections_html+="              <div class=\"action-menu-heading\">open with</div>"$'\n'
  sections_html+="$tool_html"
  sections_html+="            </div>"$'\n'
  if [[ -n "$interactive_agent_html" ]]; then
    sections_html+="            <div class=\"action-menu-section\">"$'\n'
    sections_html+="              <div class=\"action-menu-heading\">interactive</div>"$'\n'
    sections_html+="$interactive_agent_html"
    sections_html+="            </div>"$'\n'
  fi
  if [[ -n "$yolo_agent_html" ]]; then
    sections_html+="            <div class=\"action-menu-section\">"$'\n'
    sections_html+="              <div class=\"action-menu-heading\">yolo</div>"$'\n'
    sections_html+="$yolo_agent_html"
    sections_html+="            </div>"$'\n'
  fi
  if [[ -n "$agent_html" ]]; then
    sections_html+="            <div class=\"action-menu-section\">"$'\n'
    sections_html+="              <div class=\"action-menu-heading\">running</div>"$'\n'
    sections_html+="$agent_html"
    sections_html+="            </div>"$'\n'
  fi
  cat <<EOF
<details class="action-menu">
          <summary class="icon-button row-action-button" aria-label="Actions" title="Actions">
            <svg class="icon-svg" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><path d="M12 5v14"/><path d="M5 12h14"/></svg>
          </summary>
          <div class="action-menu-panel">
${sections_html}          </div>
        </details>
EOF
}

